"""audit_edges.py - Edge characterization of faithfulness.

Proposition ``oi.prop.edges`` says that, for a relation generated by licensed
steps, a surface is faithful exactly when it gives equal signatures to the
endpoints of every licensed step.
This module decides faithfulness that way, without any closure, so it is a
third derivation of the faithfulness verdict for generated relations.

It has its own licence reading and signature computation.
It shares only the pure data classes with the other checkers.
"""

from .audit_model import Generated, Instance, Record, Surface


def edge_faithfulness(
    inst: Instance, surface: Surface
) -> tuple[bool, tuple[Record, Record] | None]:
    """Decide faithfulness from the licensed steps alone.

    Returns whether the surface is faithful and, when it is not, a licensed
    edge whose endpoints it separates.
    The declared relation must be generated.
    The surface is assumed computable.
    """
    declared = inst.declared
    if not isinstance(declared, Generated):
        msg = "edge characterization applies to generated relations only"
        raise TypeError(msg)
    for step in declared.history:
        if step not in declared.licensed:
            continue
        left = [use[step.source] for use in surface.uses]
        right = [use[step.target] for use in surface.uses]
        if left != right:
            return False, (step.source, step.target)
    return True, None
