"""audit_lean.py - Emit conformance vectors for the Lean formalization.

The Python oracle audits small supplied partitions.
This module writes the same audits as Lean theorems about
``SE.OperationalIdentity`` (the ``se-theory-operational-identity`` repository),
each closed by ``decide``.
Lean then checks, with its own definitions of faithfulness, substitution, and
the four positions, the verdict, kind, and substitution flag that the Python
oracle reported.

The emitted file is a regression artifact for the Lean repository.
It is generated, so it is never edited by hand.
Vectors are chosen deterministically, a few per distinct result.
"""

from . import audit_oracle
from .audit_generate import set_partitions, supplied_from_labels
from .audit_model import Instance, Kind, Result, Verdict, identity_surface

_POSITION_PREDICATE: dict[Kind, tuple[str, str]] = {
    Kind.ALIGNED: ("Aligned", "Aligned RelSame"),
    Kind.SUB: ("SubSibling", "SubSibling RelStrictlyBelow RelLE"),
    Kind.SUPER: ("SuperSibling", "SuperSibling RelStrictlyBelow RelLE"),
    Kind.INCOMPARABLE: (
        "SiblingIncomparable",
        "SiblingIncomparable RelIncomparable RelLE",
    ),
}

_HEADER = """module -- shake: keep-all

import SE.OperationalIdentity

/-!
# Generated Conformance Vectors

SETest.OperationalIdentity.Vectors

Generated by the Python oracle of se-verification-operational-identity.
Each theorem restates an audit of small supplied partitions and is closed by
`decide`, so Lean checks the verdict, the divergence position, and the
substitution flag with its own definitions.

Do not edit by hand.
-/

namespace SETest.OperationalIdentity.Vectors

open SE.OperationalIdentity

/-- The label of a record in a partition encoded as a list of block indices. -/
def lbl (l : List Nat) (n : Nat) (r : Fin n) : Nat := l.getD r.val 0

/-- Two records carry the same label. -/
def same (l : List Nat) (n : Nat) (r s : Fin n) : Prop := lbl l n r = lbl l n s

instance (l : List Nat) (n : Nat) : DecidableRel (same l n) :=
  fun r s => inferInstanceAs (Decidable (lbl l n r = lbl l n s))
"""

_FOOTER = "\nend SETest.OperationalIdentity.Vectors\n"


def _fmt(labels: tuple[int, ...]) -> str:
    return "[" + ", ".join(str(i) for i in labels) + "]"


def _verdict_name(result: Result) -> str:
    return {
        Verdict.PASS: "Verdict.pass",
        Verdict.FAIL: "Verdict.fail",
        Verdict.INDETERMINATE: "Verdict.indeterminate",
    }[result.verdict]


def _vector(
    index: int,
    n: int,
    tau: tuple[int, ...],
    sib: tuple[int, ...],
    op: tuple[int, ...],
    result: Result,
) -> str:
    """Return the Lean theorems for one vector."""
    name = f"v{index:03d}"
    t, s, o = (f"(same {_fmt(x)} {n})" for x in (tau, sib, op))
    lines = [
        f"/-- tau {_fmt(tau)}, alternative {_fmt(sib)}, operational {_fmt(op)}. -/",
        f"theorem {name}_verdict :",
        f"    audit true (List.finRange {n}) {t} {o} = {_verdict_name(result)} := by",
        "  decide",
    ]
    equal = op == sib
    unfold = "unfold Substitution same lbl"
    lines += [
        f"theorem {name}_equal_to_alternative :",
        f"    {'' if equal else '¬ '}Substitution {o} {s} := by",
        f"  {unfold}; decide",
    ]
    if result.kind in _POSITION_PREDICATE:
        predicate, unfolds = _POSITION_PREDICATE[result.kind]
        lines += [
            f"theorem {name}_position : {predicate} {t} {o} {s} := by",
            f"  unfold {unfolds} Restrict same lbl; decide",
        ]
    return "\n".join(lines) + "\n"


def emit_vectors(sizes: tuple[int, ...] = (3, 4), per_class: int = 3) -> str:
    """Return the text of the generated Lean file.

    For each record count, the first ``per_class`` instances of every distinct
    (verdict, kind, substitution) result are emitted.
    """
    body: list[str] = []
    index = 0
    for n in sizes:
        records = tuple(f"r{i}" for i in range(n))
        taken: dict[tuple[str, str, bool], int] = {}
        labelings = list(set_partitions(n))
        for tau in labelings:
            for sib in labelings:
                for op in labelings:
                    inst = Instance(
                        records,
                        supplied_from_labels(records, tau),
                        (identity_surface("d", dict(zip(records, op, strict=True))),),
                        supplied_from_labels(records, sib),
                        label="lean-vector",
                    )
                    result = audit_oracle.audit(inst)
                    key = result.key()
                    if taken.get(key, 0) >= per_class:
                        continue
                    taken[key] = taken.get(key, 0) + 1
                    index += 1
                    body.append(_vector(index, n, tau, sib, op, result))
    return _HEADER + "\n" + "\n".join(body) + _FOOTER
